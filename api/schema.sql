CREATE TABLE IF NOT EXISTS visits (id INTEGER PRIMARY KEY, ts TEXT NOT NULL, sid TEXT NOT NULL, path TEXT, ref TEXT, referrer TEXT, country TEXT, region TEXT, city TEXT, org TEXT, asn INTEGER, device TEXT, w INTEGER, iph TEXT);
CREATE INDEX IF NOT EXISTS visits_ts ON visits (ts);
CREATE INDEX IF NOT EXISTS visits_iph ON visits (iph, ts);
CREATE TABLE IF NOT EXISTS events (id INTEGER PRIMARY KEY, ts TEXT NOT NULL, sid TEXT NOT NULL, type TEXT NOT NULL, detail TEXT);
CREATE INDEX IF NOT EXISTS events_ts ON events (ts);
CREATE TABLE IF NOT EXISTS chats (id INTEGER PRIMARY KEY, ts TEXT NOT NULL, sid TEXT, q TEXT, a TEXT, country TEXT, region TEXT, city TEXT, org TEXT, in_tok INTEGER, out_tok INTEGER, cache_read INTEGER, ms INTEGER, ok INTEGER);
CREATE INDEX IF NOT EXISTS chats_ts ON chats (ts);
CREATE TABLE IF NOT EXISTS limits (k TEXT PRIMARY KEY, n INTEGER NOT NULL, exp INTEGER NOT NULL);
